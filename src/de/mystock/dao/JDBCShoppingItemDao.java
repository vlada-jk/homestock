package de.mystock.dao;

import de.mystock.model.*;

import java.sql.*;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

/**
 * stores the entries in the MySQL table shopping_list_item.
 * <p>
 * Product data is stored in the same row as the entry.
 * Every method opens its own connection.
 */
public class JDBCShoppingItemDao implements ShoppingItemDao{

    /** URL of the database */
        private String url = "jdbc:mysql://127.0.0.1:3306/mystock_db?createDatabaseIfNotExist=true";

    //** the test database */
//    private String url = "jdbc:mysql://127.0.0.1:3306/mystock_db_test?createDatabaseIfNotExist=true";

    /** User */
    private String user = "root";
    /** Password */
    private String passwort = "";

    /** Creates a DAO */
    public JDBCShoppingItemDao() {
    }

    /**
     * Creates a DAO for the given database.
     *
     * @param url      the JDBC URL
     * @param user     the database user
     * @param passwort the password
     */
    public JDBCShoppingItemDao(String url, String user, String passwort) {
        this.url = url;
        this.user = user;
        this.passwort = passwort;
    }

    /**
     * <p>
     * Reads all rows of shopping_list_item.
     */
    @Override
    public List<ShoppingItem> findAll() {
        List<ShoppingItem> items = new ArrayList<>();
        String sql = "SELECT * FROM shopping_list_item";

        try (Connection connection = DriverManager.getConnection(url, user, passwort);
             Statement preparedStatement = connection.createStatement();
             ResultSet resultSet = preparedStatement.executeQuery(sql);
        ) {
            while (resultSet.next()) {
                int id = resultSet.getInt("id");
                String barcode = resultSet.getString("barcode");
                String name = resultSet.getString("product_name");
                String brand = resultSet.getString("brand");
                String category = resultSet.getString("category");
                //
                int quantity = resultSet.getInt("quantity");
                boolean bought = resultSet.getBoolean("bought");

                Product product = new Product(barcode, name, brand, category);
                ShoppingItem itemFromDb = new ShoppingItem(product, quantity);
                itemFromDb.setId(id);
                itemFromDb.setBought(bought);
                items.add(itemFromDb);
            }


        } catch (SQLException exception) {
            exception.printStackTrace();
        }
        return items;
    }

    /**
     * Inserts the entry as a new row and sets the id generated by the database.
     * @param item the entry to store
     */
    @Override
    public void add(ShoppingItem item) {
        String sql = "INSERT INTO shopping_list_item " +
                " (barcode, product_name, brand, category, quantity, bought)" +
                " VALUES (?, ?, ?, ?, ?, ?)";
        try (Connection connection = DriverManager.getConnection(url, user, passwort);
             PreparedStatement preparedStatement =
                     connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
        ) {
            preparedStatement.setString(1, item.getProduct().getBarcode());
            preparedStatement.setString(2, item.getProduct().getName());
            preparedStatement.setString(3, item.getProduct().getBrand());
            preparedStatement.setString(4, item.getProduct().getCategory());
            preparedStatement.setInt(5, item.getQuantity());
            preparedStatement.setBoolean(6, item.isBought());

            preparedStatement.execute();

            ResultSet generatedKeys = preparedStatement.getGeneratedKeys();
            generatedKeys.next();
            int id = generatedKeys.getInt(1);
            item.setId(id);


        } catch (SQLException exception) {
            exception.printStackTrace();
        }

    }

    /**
     * Overwrites all columns of the row with the id of the entry,
     * including quantity and the "bought" flag.
     *
     * @param item the entry to save
     */
    @Override
    public void update(ShoppingItem item) {

        String sql = """
                UPDATE shopping_list_item
                SET barcode = ?,
                    product_name = ?,
                    brand = ?,
                    category = ?,
                    quantity = ?,
                    bought = ?
                WHERE id = ?
                """;
        try (Connection connection = DriverManager.getConnection(url, user, passwort);
             PreparedStatement preparedStatement =
                     connection.prepareStatement(sql);
        ) {
            preparedStatement.setString(1, item.getProduct().getBarcode());
            preparedStatement.setString(2, item.getProduct().getName());
            preparedStatement.setString(3, item.getProduct().getBrand());
            preparedStatement.setString(4, item.getProduct().getCategory());
            preparedStatement.setInt(5, item.getQuantity());
            preparedStatement.setBoolean(6, item.isBought());
            preparedStatement.setInt(7, item.getId());

            preparedStatement.executeUpdate();


        } catch (SQLException exception) {
            exception.printStackTrace();
        }

    }

    /**
     * @param item the entry to remove
     */
    @Override
    public void remove(ShoppingItem item) {
        String sql = "DELETE FROM shopping_list_item WHERE id = ?";
        try (Connection con = DriverManager.getConnection(url, user, passwort);
             PreparedStatement preparedStatement = con.prepareStatement(sql)) {
            preparedStatement.setInt(1, item.getId());

            preparedStatement.executeUpdate();
        } catch (SQLException exception) {
            exception.printStackTrace();

        }
    }
}
