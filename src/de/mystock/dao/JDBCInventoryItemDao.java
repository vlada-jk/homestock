package de.mystock.dao;

import de.mystock.model.InventoryItem;
import de.mystock.model.Product;
import de.mystock.model.StorageLocation;
import de.mystock.model.Unit;
import javafx.application.Platform;
import javafx.scene.control.Alert;

import java.sql.*;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * stores the items in the MySQL table inventory_item.
 * <p>
 * Product data is stored in the same row as the item. Storage location and unit
 * are stored as the {@code ordinal()} of their enum.
 * Every method opens its own connection. A SQLException is not passed on:
 * its stack trace is printed and the method returns normally
 */
public class JDBCInventoryItemDao implements InventoryItemDao {

    /** JDBC URL of the database */
        private String url = "jdbc:mysql://127.0.0.1:3306/mystock_db?createDatabaseIfNotExist=true";

    //** the test database */
//    private String url = "jdbc:mysql://127.0.0.1:3306/mystock_db_test?createDatabaseIfNotExist=true";

    /**  User */
    private String user = "root";
    /** Password  */
    private String passwort = "";

    /** Creates a DAO */
    public JDBCInventoryItemDao() {
    }

    /**
     * Creates a DAO for the given database.
     *
     * @param url      the JDBC URL
     * @param user     the database user
     * @param passwort the password
     */
    public JDBCInventoryItemDao(String url, String user, String passwort) {
        this.url = url;
        this.user = user;
        this.passwort = passwort;
    }

    /**
     * <p>
     * Reads all rows of  inventory_item
     */
    @Override
    public List<InventoryItem> findAll() {

        List<InventoryItem> items = new ArrayList<>();

        String sql = "SELECT * FROM inventory_item";
        try (Connection connection = DriverManager.getConnection(url, user, passwort);
             Statement preparedStatement = connection.createStatement();
             ResultSet resultSet = preparedStatement.executeQuery(sql);
        ) {
            while (resultSet.next()) {
                int id = resultSet.getInt("id");
                String barcode = resultSet.getString("barcode");
                String name = resultSet.getString("product_name");
                String brand = resultSet.getString("brand");
                String category = resultSet.getString("category");
                //Enum in DB (int)
                int storageLocationIndex = resultSet.getInt("storage_location");
                StorageLocation storageLocation = StorageLocation.values()[storageLocationIndex];

                double contentAmount = resultSet.getDouble("content_amount");
//                String unit = resultSet.getString("unit");
                int unitIndex = resultSet.getInt("unit");
                Unit unit = Unit.values()[unitIndex];
                int quantity = resultSet.getInt("quantity");
                String expirationDate = resultSet.getString("expiration_date");
                String notes = resultSet.getString("notes");

                Product product = new Product(barcode, name, brand, category);
                InventoryItem itemFromDb = new InventoryItem(product,
                        storageLocation,
                        contentAmount,
                        unit,
//                        Unit.valueOf(unit.toUpperCase()),
                        quantity,
                         LocalDate.parse(expirationDate),
                        // raus nehmen
//                        expirationDate == null
//                                ? null
//                                : LocalDate.parse(expirationDate),
                        notes);
                itemFromDb.setId(id);
                items.add(itemFromDb);
            }


        } catch (SQLException exception) {

//            throw new RuntimeException("Could not remove item " + id, e);
//             Alert new Alert
            exception.printStackTrace();
//            Platform.exit();

        }
        return items;
    }

    /**
     * Inserts the item as a new row and sets the id generated by the database.
     * @param item the item to store
     */
    @Override
    public void add(InventoryItem item) {
        String sql = "INSERT INTO inventory_item " +
                " VALUE (NULL, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

        try (Connection connection = DriverManager.getConnection(url, user, passwort);
             PreparedStatement preparedStatement =
                     connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
        ) {
            preparedStatement.setString(1, item.getProduct().getBarcode());
            preparedStatement.setString(2, item.getProduct().getName());
            preparedStatement.setString(3, item.getProduct().getBrand());
            preparedStatement.setString(4, item.getProduct().getCategory());
            preparedStatement.setInt(5, item.getStorageLocation().ordinal());
            preparedStatement.setDouble(6, item.getContentAmount());
            preparedStatement.setInt(7, item.getUnit().ordinal());
            preparedStatement.setInt(8, item.getQuantity());
            preparedStatement.setObject(9, item.getExpirationDate());
            preparedStatement.setString(10, item.getNotes());

            preparedStatement.execute();

            ResultSet generatedKeys = preparedStatement.getGeneratedKeys();
            generatedKeys.next();
            int id = generatedKeys.getInt(1);
            item.setId(id);


        } catch (SQLException exception) {
            exception.printStackTrace();
        }

    }

    /**
     * Overwrites all columns of the row with the id of the item.
     *
     * @param item the item to save
     */
    @Override
    public void update(InventoryItem item) {
        String sql = """
                UPDATE inventory_item
                SET barcode = ?,
                    product_name = ?,
                    brand = ?,
                    category = ?,
                    storage_location = ?,
                    content_amount = ?,
                    unit = ?,
                    quantity = ?,
                    expiration_date = ?,
                    notes = ?
                WHERE id = ?
                """;

        try (Connection connection = DriverManager.getConnection(url, user, passwort);
             PreparedStatement preparedStatement =
                     connection.prepareStatement(sql);
        ) {
            preparedStatement.setString(1, item.getProduct().getBarcode());
            preparedStatement.setString(2, item.getProduct().getName());
            preparedStatement.setString(3, item.getProduct().getBrand());
            preparedStatement.setString(4, item.getProduct().getCategory());
            preparedStatement.setInt(5, item.getStorageLocation().ordinal());
            preparedStatement.setDouble(6, item.getContentAmount());
            preparedStatement.setInt(7, item.getUnit().ordinal());
            preparedStatement.setInt(8, item.getQuantity());
            preparedStatement.setObject(9, item.getExpirationDate());
            preparedStatement.setString(10, item.getNotes());
            preparedStatement.setInt(11, item.getId());

            preparedStatement.executeUpdate();


        } catch (SQLException exception) {
            exception.printStackTrace();
        }


    }

    /**
     * @param item the item to remove
     */
    @Override
    // statt id InventoryItem
    public void remove(InventoryItem item) {
        String sql = "DELETE FROM inventory_item WHERE id = ?";
        try (Connection con = DriverManager.getConnection(url, user, passwort);
             PreparedStatement preparedStatement = con.prepareStatement(sql)) {
            preparedStatement.setInt(1, item.getId());

            preparedStatement.executeUpdate();
        } catch (SQLException exception) {
            exception.printStackTrace();
        }
    }
}
